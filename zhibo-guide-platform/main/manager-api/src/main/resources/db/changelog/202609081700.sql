CREATE TABLE IF NOT EXISTS `museum_exhibit` (
    `id` varchar(64) NOT NULL COMMENT '展品ID，同时作为知识库 exhibit_id',
    `museum` varchar(120) NOT NULL COMMENT '博物馆名称',
    `exhibition` varchar(120) DEFAULT NULL COMMENT '展览名称',
    `name` varchar(120) NOT NULL COMMENT '展品名称',
    `era` varchar(80) NOT NULL COMMENT '年代',
    `material` varchar(120) NOT NULL COMMENT '材质',
    `category` varchar(80) NOT NULL COMMENT '类别',
    `summary` varchar(1200) NOT NULL COMMENT '游客端摘要',
    `image_url` varchar(1000) DEFAULT NULL COMMENT '游客端公开图片地址',
    `image_sha256` char(64) DEFAULT NULL COMMENT '图片校验值',
    `tags` json DEFAULT NULL COMMENT '主题标签',
    `observations` json DEFAULT NULL COMMENT '观察提示',
    `sources` json DEFAULT NULL COMMENT '公开资料来源',
    `status` varchar(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT/PUBLISHED/OFFLINE',
    `sort` int NOT NULL DEFAULT 0 COMMENT '游客端排序',
    `published_at` datetime DEFAULT NULL COMMENT '最近发布时间',
    `creator` bigint DEFAULT NULL COMMENT '创建者',
    `create_date` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updater` bigint DEFAULT NULL COMMENT '更新者',
    `update_date` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_museum_exhibit_status_sort` (`status`, `sort`),
    KEY `idx_museum_exhibit_museum` (`museum`, `exhibition`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='博物馆结构化展品内容';
